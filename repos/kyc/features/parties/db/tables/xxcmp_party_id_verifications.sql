-- 16e Party logic (party feature: pages 20-24, and the common party region on the Global Page)
--   XXCMP_PARTY_PKG: the rules and save of the common party form (Party dialog 24, Create Request
--   step 1 on 201, new owner / officer on 23), party status, owner / officer rules, the merge of a
--   duplicate party (Compliance) and the common party card. Runs after 16b/16c: the merge re-points
--   requests, cases, screenings, alerts, notes and beneficial-owner decisions.
-- Organisation / individual share one column per pair: JURISDICTION = country / nationality,
-- REGISTRATION_NUMBER = registration / ID number, ENTITY_TYPE = entity / ID type (lookup
-- ENTITY_TYPE / ID_DOCUMENT_TYPE), INCORPORATION_DATE = incorporation / birth date.
-- Idempotent: safe on install and on every upgrade.
--------------------------------------------------------------------------------
-- the specification is in 16e0-party-pkg-spec.sql (runs before 16b)


-- release 74 (R14): party verifications, created before the body that uses them.
--   XXCMP_PARTY_ID_VERIFICATIONS   identity document checks of an individual: manual only (few a month, no
--                                  government integration planned).
--   XXCMP_PARTY_REGISTRY_CHECKS    company registry (KYB) checks of an organisation: recorded by hand now; later a
--                                  registry provider (COMMON Integration setup, purpose REGISTRY_LOOKUP) fills the
--                                  same row (SOURCE = API, ORIGINAL_RESPONSE) and a person reviews it.
--   A case may link the check it made. Lookups, attachment entities and data security rules: 18e.
begin
    if xxfnd_ddl_pkg.create_table('XXCMP_PARTY_ID_VERIFICATIONS', q'~create table xxcmp_party_id_verifications (
    id_verification_id     number generated by default on null as identity,
    party_id               number         not null,
    case_id                number,
    document_type          varchar2(30)   not null,
    document_number        varchar2(100)  not null,
    issuing_country        varchar2(30),
    issue_date             date,
    expiry_date            date,
    verification_method    varchar2(30)   not null,
    verification_result    varchar2(30)   not null,
    verified_by            varchar2(255)  not null,
    verified_date          date           default trunc(sysdate) not null,
    notes                  varchar2(4000),
    created_by             varchar2(255)  not null,
    creation_date          timestamp      not null,
    last_updated_by        varchar2(255)  not null,
    last_update_date       timestamp      not null,
    last_update_login      varchar2(255),
    object_version_number  number         default 1 not null,
    constraint xxcmp_party_id_verif_pk primary key (id_verification_id),
    constraint xxcmp_party_id_verif_fk1 foreign key (party_id) references xxcmp_parties (party_id),
    constraint xxcmp_party_id_verif_fk2 foreign key (case_id) references xxcmp_cases (case_id),
    constraint xxcmp_party_id_verif_ck1 check (verification_result in ('VERIFIED','NOT_VERIFIED','INCONCLUSIVE')),
    constraint xxcmp_party_id_verif_ck2 check (expiry_date is null or issue_date is null or expiry_date >= issue_date)
)~') then
        xxfnd_ddl_pkg.run(q'~comment on table xxcmp_party_id_verifications is 'Identity document checks of a party, recorded by hand (document, how it was checked, result, who and when). The document copy is an attachment of the row.'~');
        xxfnd_ddl_pkg.run(q'~comment on column xxcmp_party_id_verifications.verification_method is 'Lookup ID_VERIFICATION_METHOD: original seen, certified copy, video call, government portal.'~');
        xxfnd_ddl_pkg.run('create index xxcmp_party_id_verif_n1 on xxcmp_party_id_verifications (party_id)');
        xxfnd_ddl_pkg.run('create index xxcmp_party_id_verif_n2 on xxcmp_party_id_verifications (case_id)');
    end if;
    xxfnd_schema_pkg.create_who_trigger('XXCMP_PARTY_ID_VERIFICATIONS');

    if xxfnd_ddl_pkg.create_table('XXCMP_PARTY_REGISTRY_CHECKS', q'~create table xxcmp_party_registry_checks (
    registry_check_id      number generated by default on null as identity,
    party_id               number         not null,
    case_id                number,
    source                 varchar2(30)   default 'MANUAL' not null,
    endpoint_code          varchar2(30),
    registry_name          varchar2(200),
    external_reference     varchar2(200),
    registered_name        varchar2(400),
    registration_number    varchar2(100),
    registration_status    varchar2(30),
    incorporation_date     date,
    registered_address     varchar2(1000),
    officers_summary       varchar2(4000),
    owners_summary         varchar2(4000),
    original_response      clob,
    check_result           varchar2(30)   not null,
    checked_by             varchar2(255)  not null,
    checked_date           date           default trunc(sysdate) not null,
    reviewed_by            varchar2(255),
    reviewed_date          date,
    changed_by_person_flag varchar2(1)    default 'N' not null,
    notes                  varchar2(4000),
    created_by             varchar2(255)  not null,
    creation_date          timestamp      not null,
    last_updated_by        varchar2(255)  not null,
    last_update_date       timestamp      not null,
    last_update_login      varchar2(255),
    object_version_number  number         default 1 not null,
    constraint xxcmp_party_reg_check_pk primary key (registry_check_id),
    constraint xxcmp_party_reg_check_fk1 foreign key (party_id) references xxcmp_parties (party_id),
    constraint xxcmp_party_reg_check_fk2 foreign key (case_id) references xxcmp_cases (case_id),
    constraint xxcmp_party_reg_check_ck1 check (source in ('MANUAL','API')),
    constraint xxcmp_party_reg_check_ck2 check (check_result in ('MATCH','MISMATCH','NOT_FOUND')),
    constraint xxcmp_party_reg_check_ck3 check (changed_by_person_flag in ('Y','N')),
    constraint xxcmp_party_reg_check_ck4 check (source = 'MANUAL' or endpoint_code is not null)
)~') then
        xxfnd_ddl_pkg.run(q'~comment on table xxcmp_party_registry_checks is 'Company registry (KYB) checks of a party: what the registry holds against the party record. SOURCE MANUAL = typed by a person; API = filled by the registry provider (ENDPOINT_CODE, ORIGINAL_RESPONSE kept unchanged), then reviewed by a person (REVIEWED_BY); CHANGED_BY_PERSON_FLAG = a person corrected the provider data.'~');
        xxfnd_ddl_pkg.run(q'~comment on column xxcmp_party_registry_checks.endpoint_code is 'COMMON Integration endpoint (XXFND_INTEGRATION_ENDPOINTS, type REGISTRY_PROVIDER) that supplied the data; null when typed by hand.'~');
        xxfnd_ddl_pkg.run('create index xxcmp_party_reg_check_n1 on xxcmp_party_registry_checks (party_id)');
        xxfnd_ddl_pkg.run('create index xxcmp_party_reg_check_n2 on xxcmp_party_registry_checks (case_id)');
    end if;
    xxfnd_schema_pkg.create_who_trigger('XXCMP_PARTY_REGISTRY_CHECKS');
end;
