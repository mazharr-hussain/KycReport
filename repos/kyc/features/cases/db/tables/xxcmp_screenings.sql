
create table if not exists xxcmp_screenings (
    screening_id           number generated by default on null as identity,
    case_id                number         not null,
    party_id               number         not null,
    screening_type         varchar2(30)   not null,
    match_status           varchar2(30)   default 'NO_MATCH' not null,
    pep_flag               varchar2(1)    default 'N' not null,
    sanctions_flag         varchar2(1)    default 'N' not null,
    adverse_media_flag     varchar2(1)    default 'N' not null,
    capture_method         varchar2(30)   default 'MANUAL' not null,
    source_reference       varchar2(1000),
    result_notes           varchar2(4000),
    screened_date          date           default trunc(sysdate) not null,
    -- standard WHO columns
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxcmp_screenings_pk primary key (screening_id),
    constraint xxcmp_screenings_fk1 foreign key (case_id) references xxcmp_cases (case_id),
    constraint xxcmp_screenings_fk2 foreign key (party_id) references xxcmp_parties (party_id),
    constraint xxcmp_screenings_ck1 check (screening_type in ('REGISTRY','SANCTIONS','PEP','ADVERSE_MEDIA')),
    constraint xxcmp_screenings_ck2 check (match_status in ('NO_MATCH','POTENTIAL_MATCH','CONFIRMED_MATCH','FALSE_POSITIVE')),
    constraint xxcmp_screenings_ck3 check (pep_flag in ('Y','N') and sanctions_flag in ('Y','N') and adverse_media_flag in ('Y','N')),
    constraint xxcmp_screenings_ck4 check (capture_method in ('MANUAL','API'))
);
comment on table xxcmp_screenings is 'One screening event per check, with all its flags. A confirmed match or a PEP flag forces the case into Enhanced KYC.';
comment on column xxcmp_screenings.risk_tier is 'Risk level of the screened party (lookup RISK_TIER). RESULT_NOTES = the conclusion, SOURCE_REFERENCE = the source, MATCH_STATUS = the results.';
--------------------------------------------------------------------------------
-- 16s Case component - XXCMP_CASE_PKG body (release 74: own script, R1). KYC only (XXCUS).
--   The case logic: opening a case (the only CREATE_CASE), sections, screening, investigation, submit for approval,
--   approval levels and decisions, withdraw, case RFIs. The request is approved by XXCMP_REQUEST_PKG; the party by
--   XXCMP_PARTY_PKG. The specification is in 16b (with the tables).
-- Idempotent: the case record tables only when missing, columns as checked steps, then create or replace.
--------------------------------------------------------------------------------
-- release 74 (R14, R19): case records ready for integration, created before the body that uses them.
--   XXCMP_SCREENINGS (checked steps): the provider (ENDPOINT_CODE), its ORIGINAL_RESPONSE kept unchanged, REVIEWED_BY /
--     REVIEWED_DATE and CHANGED_BY_PERSON_FLAG - by hand now (CAPTURE_METHOD MANUAL), from a screening provider later (API).
--   XXCMP_FIU_REPORTS: the suspicious transaction / activity report to the FIU (goAML): draft, approval by a second
--     person, filing reference and date; filed by hand now, by a goAML integration later (SOURCE API).
--   XXCMP_CASE_FUNDS: guided source of funds / wealth - what the money comes from (category), the evidence expected for
--     it (lookup FUNDS_CATEGORY tag), the bank data seen (typed by hand now, from a bank data provider later).
--   Lookups, data security rules and integration purposes: 18e.
begin
    xxfnd_ddl_pkg.add_column('XXCMP_SCREENINGS', 'ENDPOINT_CODE', 'varchar2(30)');
    xxfnd_ddl_pkg.add_column('XXCMP_SCREENINGS', 'ORIGINAL_RESPONSE', 'clob');
    xxfnd_ddl_pkg.add_column('XXCMP_SCREENINGS', 'REVIEWED_BY', 'varchar2(255)');
    xxfnd_ddl_pkg.add_column('XXCMP_SCREENINGS', 'REVIEWED_DATE', 'date');
    xxfnd_ddl_pkg.add_column('XXCMP_SCREENINGS', 'CHANGED_BY_PERSON_FLAG', 'varchar2(1) default ''N'' not null');
    xxfnd_ddl_pkg.add_constraint('XXCMP_SCREENINGS', 'XXCMP_SCREENINGS_CK5', 'check (changed_by_person_flag in (''Y'',''N''))');

    if xxfnd_ddl_pkg.create_table('XXCMP_FIU_REPORTS', q'~create table xxcmp_fiu_reports (
    fiu_report_id          number generated by default on null as identity,
    case_id                number         not null,
    party_id               number         not null,
    report_type            varchar2(30)   not null,
    report_status          varchar2(30)   default 'DRAFT' not null,
    grounds                varchar2(4000) not null,
    transactions_summary   varchar2(4000),
    prepared_by            varchar2(255)  not null,
    approved_by            varchar2(255),
    approved_date          date,
    goaml_reference        varchar2(100),
    filed_by               varchar2(255),
    filed_date             date,
    source                 varchar2(30)   default 'MANUAL' not null,
    endpoint_code          varchar2(30),
    original_response      clob,
    notes                  varchar2(4000),
    created_by             varchar2(255)  not null,
    creation_date          timestamp      not null,
    last_updated_by        varchar2(255)  not null,
    last_update_date       timestamp      not null,
    last_update_login      varchar2(255),
    object_version_number  number         default 1 not null,
    constraint xxcmp_fiu_reports_pk primary key (fiu_report_id),
    constraint xxcmp_fiu_reports_fk1 foreign key (case_id) references xxcmp_cases (case_id),
    constraint xxcmp_fiu_reports_fk2 foreign key (party_id) references xxcmp_parties (party_id),
    constraint xxcmp_fiu_reports_ck1 check (report_status in ('DRAFT','APPROVED','FILED','CANCELLED')),
    constraint xxcmp_fiu_reports_ck2 check (source in ('MANUAL','API')),
    constraint xxcmp_fiu_reports_ck3 check (report_status <> 'FILED' or (goaml_reference is not null and filed_date is not null))
)~') then
        xxfnd_ddl_pkg.run(q'~comment on table xxcmp_fiu_reports is 'Suspicious transaction / activity reports to the FIU (goAML) raised from a case: prepared, approved by a second person, filed (reference and date). Filed by hand now; SOURCE API, ENDPOINT_CODE and ORIGINAL_RESPONSE are for a goAML integration later.'~');
        xxfnd_ddl_pkg.run('create index xxcmp_fiu_reports_n1 on xxcmp_fiu_reports (case_id)');
    end if;
    xxfnd_schema_pkg.create_who_trigger('XXCMP_FIU_REPORTS');

    if xxfnd_ddl_pkg.create_table('XXCMP_CASE_FUNDS', q'~create table xxcmp_case_funds (
    case_funds_id          number generated by default on null as identity,
    case_id                number         not null,
    party_id               number         not null,
    funds_type             varchar2(30)   not null,
    category               varchar2(30)   not null,
    description            varchar2(1000),
    amount                 number,
    currency_code          varchar2(3),
    evidence_type          varchar2(30),
    bank_name              varchar2(200),
    account_reference      varchar2(100),
    period_from            date,
    period_to              date,
    source                 varchar2(30)   default 'MANUAL' not null,
    endpoint_code          varchar2(30),
    original_response      clob,
    verified_flag          varchar2(1)    default 'N' not null,
    verified_by            varchar2(255),
    verified_date          date,
    notes                  varchar2(4000),
    created_by             varchar2(255)  not null,
    creation_date          timestamp      not null,
    last_updated_by        varchar2(255)  not null,
    last_update_date       timestamp      not null,
    last_update_login      varchar2(255),
    object_version_number  number         default 1 not null,
    constraint xxcmp_case_funds_pk primary key (case_funds_id),
    constraint xxcmp_case_funds_fk1 foreign key (case_id) references xxcmp_cases (case_id),
    constraint xxcmp_case_funds_fk2 foreign key (party_id) references xxcmp_parties (party_id),
    constraint xxcmp_case_funds_ck1 check (funds_type in ('SOF','SOW')),
    constraint xxcmp_case_funds_ck2 check (source in ('MANUAL','API')),
    constraint xxcmp_case_funds_ck3 check (verified_flag in ('Y','N')),
    constraint xxcmp_case_funds_ck4 check (amount is null or amount >= 0),
    constraint xxcmp_case_funds_ck5 check (period_to is null or period_from is null or period_to >= period_from)
)~') then
        xxfnd_ddl_pkg.run(q'~comment on table xxcmp_case_funds is 'Guided source of funds (SOF) and source of wealth (SOW) of a case: the category, the evidence expected for it (lookup FUNDS_CATEGORY tag) and the bank data seen. Typed by hand now; SOURCE API, ENDPOINT_CODE and ORIGINAL_RESPONSE are for a bank data provider later.'~');
        xxfnd_ddl_pkg.run('create index xxcmp_case_funds_n1 on xxcmp_case_funds (case_id)');
    end if;
    xxfnd_schema_pkg.create_who_trigger('XXCMP_CASE_FUNDS');
end;
