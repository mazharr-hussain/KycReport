--------------------------------------------------------------------------------
-- 16c Monitoring  (release R14)
-- Ongoing monitoring of approved parties.
--   XXCMP_ALERT_RULES   what to watch (review due/overdue, case SLA, expiring documents, adverse screening),
--                       who is told, and whether a review starts on its own
--   XXCMP_ALERTS        the alerts raised by the rules (one per rule and subject), acknowledged or closed
--   XXCMP_WATCHLIST_V   each approved party with its latest approved case and where its review stands
--   XXCMP_MONITOR_PKG   daily run (periodic reviews, alerts), early reassessment, acknowledgement
-- Idempotent: safe on install and on every upgrade.
--------------------------------------------------------------------------------
create table if not exists xxcmp_alert_rules (
    alert_rule_id          number generated by default on null as identity,
    rule_code              varchar2(30)   not null,
    rule_name              varchar2(240)  not null,
    alert_type             varchar2(30)   not null,
    days_before            number         default 0 not null,
    risk_tier              varchar2(30),
    recipient_role_code    varchar2(30),
    notify_flag            varchar2(1)    default 'Y' not null,
    start_review_flag      varchar2(1)    default 'N' not null,
    enabled_flag           varchar2(1)    default 'Y' not null,
    description            varchar2(1000),
    -- standard WHO columns
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxcmp_alert_rules_pk primary key (alert_rule_id),
    constraint xxcmp_alert_rules_uk1 unique (rule_code),
    constraint xxcmp_alert_rules_ck1 check (alert_type in ('REVIEW_DUE','REVIEW_OVERDUE','SLA_BREACH','DOCUMENT_EXPIRY','ADVERSE_SCREENING')),
    constraint xxcmp_alert_rules_ck2 check (notify_flag in ('Y','N')),
    constraint xxcmp_alert_rules_ck3 check (start_review_flag in ('Y','N')),
    constraint xxcmp_alert_rules_ck4 check (enabled_flag in ('Y','N')),
    constraint xxcmp_alert_rules_ck5 check (days_before >= 0)
);
comment on table xxcmp_alert_rules is 'Monitoring rules: what raises an alert, how many days ahead (or of grace), for which risk tier, who is notified and whether an early review starts automatically.';
comment on column xxcmp_alert_rules.days_before is 'REVIEW_DUE / DOCUMENT_EXPIRY: days ahead; REVIEW_OVERDUE / SLA_BREACH: days of grace; ADVERSE_SCREENING: not used.';
comment on column xxcmp_alert_rules.start_review_flag is 'Y: the daily run also starts an event-triggered review (DOCUMENT_EXPIRY once expired, ADVERSE_SCREENING).';
