
create table if not exists xxcmp_alerts (
    alert_id               number generated by default on null as identity,
    alert_rule_id          number         not null,
    alert_key              varchar2(200)  not null,
    party_id               number,
    case_id                number,
    alert_message          varchar2(1000) not null,
    due_date               date,
    alert_status           varchar2(30)   default 'OPEN' not null,
    acknowledged_by        varchar2(255),
    acknowledged_date      timestamp,
    review_request_id      number,
    -- standard WHO columns
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxcmp_alerts_pk primary key (alert_id),
    constraint xxcmp_alerts_uk1 unique (alert_rule_id, alert_key),
    constraint xxcmp_alerts_fk1 foreign key (alert_rule_id) references xxcmp_alert_rules (alert_rule_id),
    constraint xxcmp_alerts_fk2 foreign key (party_id) references xxcmp_parties (party_id),
    constraint xxcmp_alerts_fk3 foreign key (case_id) references xxcmp_cases (case_id),
    constraint xxcmp_alerts_fk4 foreign key (review_request_id) references xxcmp_requests (request_id),
    constraint xxcmp_alerts_ck1 check (alert_status in ('OPEN','ACKNOWLEDGED','CLOSED'))
);
comment on table xxcmp_alerts is 'Alerts raised by the monitoring rules; the key (per rule) keeps one alert per subject, e.g. per case and review date.';
create index if not exists xxcmp_alerts_n1 on xxcmp_alerts (party_id, alert_status);
create index if not exists xxcmp_alerts_n2 on xxcmp_alerts (case_id);
