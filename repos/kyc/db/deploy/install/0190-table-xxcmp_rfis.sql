
--==============================================================================
-- 0.2  REQUEST FOR INFORMATION
--==============================================================================
begin
    if xxfnd_ddl_pkg.create_table('XXCMP_RFIS', q'~create table xxcmp_rfis (
    rfi_id                 number generated by default on null as identity,
    rfi_number             varchar2(30)   not null,
    entity_name            varchar2(60)   not null,
    pk1_value              varchar2(150)  not null,
    response_task_id       number,
    review_task_id         number,
    recipient_type         varchar2(30)   not null,
    recipient_user_name    varchar2(255),
    recipient_party_contact_id number,
    rfi_category           varchar2(30)   not null,
    description            varchar2(4000) not null,
    continue_other_work_flag varchar2(1)  not null,
    rfi_status             varchar2(30)   default 'WAITING_FOR_INFORMATION' not null,
    due_date               date,
    response_token_hash    varchar2(128),
    token_expiry_date      timestamp,
    response_text          clob,
    responded_date         timestamp,
    resolved_date          timestamp,
    resolution_notes       varchar2(4000),
    -- standard WHO columns
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxcmp_rfis_pk primary key (rfi_id),
    constraint xxcmp_rfis_uk1 unique (rfi_number),
    constraint xxcmp_rfis_fk1 foreign key (entity_name) references xxfusion.xxfnd_document_entities (entity_name),
    constraint xxcmp_rfis_fk3 foreign key (recipient_party_contact_id) references xxcmp_party_contacts (party_contact_id),
    constraint xxcmp_rfis_ck1 check (recipient_type in ('REQUESTING_DEPARTMENT','EXTERNAL_PARTY')),
    constraint xxcmp_rfis_ck2 check (continue_other_work_flag in ('Y','N')),
    constraint xxcmp_rfis_ck3 check (rfi_status in
        ('WAITING_FOR_INFORMATION','ON_HOLD_PENDING','ON_HOLD_INVESTIGATION','RESOLVED','REJECTED_RETURNED','CANCELLED')),
    constraint xxcmp_rfis_ck4 check (
        (recipient_type = 'REQUESTING_DEPARTMENT' and recipient_user_name is not null) or
        (recipient_type = 'EXTERNAL_PARTY'        and recipient_party_contact_id is not null))
)~') then
        xxfnd_ddl_pkg.run(q'~create index xxcmp_rfis_n1 on xxcmp_rfis (entity_name, pk1_value)~');
        xxfnd_ddl_pkg.run(q'~create unique index xxcmp_rfis_u2 on xxcmp_rfis (response_token_hash)~');
        xxfnd_ddl_pkg.run(q'~comment on table  xxcmp_rfis is 'Requests for Information raised at document checklist review, investigation or approval return. Attaches generically so it does not depend on Module 1 or 2 tables.'~');
        xxfnd_ddl_pkg.run(q'~comment on column xxcmp_rfis.response_task_id is 'APEX action task RFI_RESPONSE for an internal recipient.'~');
        xxfnd_ddl_pkg.run(q'~comment on column xxcmp_rfis.review_task_id is 'APEX action task RFI_REVIEW for the Compliance team once a response arrives.'~');
        xxfnd_ddl_pkg.run(q'~comment on column xxcmp_rfis.response_token_hash is 'SHA-256 hash of the one-time token emailed to an external party. The token itself is never stored.'~');
    end if;
end;
