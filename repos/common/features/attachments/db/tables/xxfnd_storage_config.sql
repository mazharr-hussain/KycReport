    xxfnd_ddl_pkg.add_column('XXFND_DOCUMENTS', 'SERVER_CODE', 'varchar2(255)');
    xxfnd_ddl_pkg.add_column('XXFND_DOCUMENTS', 'STORAGE_CONTAINER', 'varchar2(500)');
end;
