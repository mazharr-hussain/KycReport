
create table if not exists xxfnd_users (
    user_id                number generated by default on null as identity,
    user_name              varchar2(255)  not null,
    user_type              varchar2(10)   not null,
    employee_id            number,
    full_name              varchar2(240),
    email_address          varchar2(320),
    enabled_flag           varchar2(1)    default 'Y' not null,
    start_date_active      date           default trunc(sysdate) not null,
    end_date_active        date,
    description            varchar2(1000),
    -- standard WHO columns
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_users_pk primary key (user_id),
    constraint xxfnd_users_uk1 unique (user_name),
    constraint xxfnd_users_uk2 unique (employee_id),
    constraint xxfnd_users_fk1 foreign key (employee_id) references xxhr_employees (employee_id),
    constraint xxfnd_users_ck1 check (user_type in ('SSO','LOCAL')),
    constraint xxfnd_users_ck2 check ((user_type = 'SSO' and employee_id is not null) or (user_type = 'LOCAL' and employee_id is null)),
    constraint xxfnd_users_ck3 check (enabled_flag in ('Y','N')),
    constraint xxfnd_users_ck4 check (user_name = upper(user_name)),
    constraint xxfnd_users_ck5 check (end_date_active is null or end_date_active >= start_date_active)
);
comment on table xxfnd_users is 'Users of all applications. SSO = linked to an employee, signs in with the identity domain (no password); LOCAL = no employee, Oracle APEX account (APEX keeps the password).';
comment on column xxfnd_users.user_name is 'Sign-in name, upper case. SSO: the employee''s user name (identity-domain user name); LOCAL: the APEX account name.';
