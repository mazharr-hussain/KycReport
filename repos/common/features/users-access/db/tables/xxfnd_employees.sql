begin
    if xxfnd_ddl_pkg.create_table('XXFND_EMPLOYEES', q'~create table xxfnd_employees (
    employee_id            number generated by default on null as identity,
    source_type            varchar2(20)   default 'LOCAL' not null,
    fusion_person_id       number,
    fusion_person_number   varchar2(30),
    fusion_user_id         varchar2(64),
    user_name              varchar2(255)  not null,
    full_name              varchar2(240)  not null,
    email_address          varchar2(320)  not null,
    department_name        varchar2(240),
    job_title              varchar2(240),
    last_sync_date         timestamp,
    enabled_flag           varchar2(1)    default 'Y' not null,
    start_date_active      date           default trunc(sysdate) not null,
    end_date_active        date,
    -- standard WHO columns
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_employees_pk primary key (employee_id),
    constraint xxfnd_employees_uk1 unique (user_name),
    constraint xxfnd_employees_uk2 unique (email_address),
    constraint xxfnd_employees_ck1 check (source_type in ('FUSION','LOCAL')),
    constraint xxfnd_employees_ck2 check (
        (source_type = 'FUSION' and fusion_person_id is not null) or
        (source_type = 'LOCAL'  and fusion_person_id is null)),
    constraint xxfnd_employees_ck3 check (enabled_flag in ('Y','N')),
    constraint xxfnd_employees_ck4 check (user_name = upper(user_name))
)~') then
        xxfnd_ddl_pkg.run(q'~create unique index xxfnd_employees_u3 on xxfnd_employees (fusion_person_id)~');
        xxfnd_ddl_pkg.run(q'~comment on table  xxfnd_employees is 'One row per person. FUSION rows are maintained by the Fusion HCM sync and are read-only in the application; LOCAL rows are maintained by an administrator.'~');
        xxfnd_ddl_pkg.run(q'~comment on column xxfnd_employees.user_name is 'Matches APP_USER after sign-in (upper case). This is how a session resolves to a person.'~');
    end if;
end;
/
-- 04a Employees: Fusion user account (release 37). USER_NAME = the Fusion / identity-domain user name used by single
-- sign-on, EMAIL_ADDRESS = the work e-mail, FUSION_USER_ID = the Fusion user account (HCM userAccounts UserId).
-- Idempotent.

declare
    l_count pls_integer;
begin
    select count(*) into l_count from user_tab_columns
     where table_name = 'XXFND_EMPLOYEES' and column_name = 'FUSION_USER_ID';
    if l_count = 0 then
        execute immediate 'alter table xxfnd_employees add (fusion_user_id varchar2(64))';
    end if;
end;
/
comment on column xxfnd_employees.user_name is 'Sign-in name: the Fusion / identity-domain user name (upper case); the work e-mail until the HCM sync finds a user account.';
comment on column xxfnd_employees.fusion_user_id is 'Fusion user account id (HCM userAccounts UserId), set by the HCM sync.';
