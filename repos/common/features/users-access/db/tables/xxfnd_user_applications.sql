--------------------------------------------------------------------------------
-- 09a Security model (release 96, agreed with the user): every row belongs to an application.
--   XXFND_USER_APPLICATIONS  a user's access to an application (one user, several applications)
--   XXFND_ROLE_MEMBERS       roles inside roles (a role = any mix of child roles, privileges and data access)
--   XXHR_ORGANIZATIONS      departments, organizations, business units ... (local now, Fusion HCM later)
--   XXFND_DATA_DIMENSIONS    what data access is decided by (Department, Country, ...) and where its values come from
--   XXFND_DATA_OBJECTS       a secured table: its dimension column and its owner column
--   XXFND_ROLE_DATA_ACCESS   role x data object x level (ALL records, given VALUES, OWN records)
--   XXFND_ASSIGNMENT_VALUES  the values of a user's role assignment per dimension (data object empty = the default
--                            for every object of the dimension; a data object = an override for that object only)
--   XXFND_USER_ROLE_TREE_V   a user's roles including the roles inside them (privileges and data access add up)
-- Data access only through roles (no direct grant to a user); it decides which records, privileges decide what.
-- Installed before 09b (its packages read these objects). Tables only when missing; a re-run changes nothing.
--------------------------------------------------------------------------------
declare
    l_new boolean;
begin
    l_new := xxfnd_ddl_pkg.create_table('XXFND_USER_APPLICATIONS', q'~create table xxfnd_user_applications (
    user_application_id    number generated by default on null as identity,
    user_id                number         not null,
    application_code       varchar2(30)   not null,
    start_date_active      date           default trunc(sysdate) not null,
    end_date_active        date,
    enabled_flag           varchar2(1)    default 'Y' not null,
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_user_applications_pk primary key (user_application_id),
    constraint xxfnd_user_applications_uk1 unique (user_id, application_code),
    constraint xxfnd_user_applications_fk1 foreign key (user_id) references xxfnd_users (user_id) on delete cascade,
    constraint xxfnd_user_applications_fk2 foreign key (application_code)
        references xxfnd_applications (application_code) on delete cascade,
    constraint xxfnd_user_applications_ck1 check (enabled_flag in ('Y','N')),
    constraint xxfnd_user_applications_ck2 check (end_date_active is null or end_date_active >= start_date_active)
)~');
    if l_new then
        xxfnd_ddl_pkg.run(q'~create index xxfnd_user_applications_n1 on xxfnd_user_applications (application_code)~');
        xxfnd_ddl_pkg.run(q'~comment on table xxfnd_user_applications is 'Release 96: the applications a user may use. A role of an application is assigned only to a user with access to it; ending the access ends the roles there.'~');
    end if;

    l_new := xxfnd_ddl_pkg.create_table('XXFND_ROLE_MEMBERS', q'~create table xxfnd_role_members (
    role_code              varchar2(30)   not null,
    member_role_code       varchar2(30)   not null,
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_role_members_pk primary key (role_code, member_role_code),
    constraint xxfnd_role_members_fk1 foreign key (role_code) references xxfnd_roles (role_code) on delete cascade,
    constraint xxfnd_role_members_fk2 foreign key (member_role_code) references xxfnd_roles (role_code) on delete cascade,
    constraint xxfnd_role_members_ck1 check (role_code <> member_role_code)
)~');
    if l_new then
        xxfnd_ddl_pkg.run(q'~create index xxfnd_role_members_n1 on xxfnd_role_members (member_role_code)~');
        xxfnd_ddl_pkg.run(q'~comment on table xxfnd_role_members is 'Release 96: roles inside roles. A user holding ROLE_CODE also has MEMBER_ROLE_CODE (and its members), with their privileges and data access.'~');
    end if;

    l_new := xxfnd_ddl_pkg.create_table('XXHR_ORGANIZATIONS', q'~create table xxhr_organizations (
    organization_id        number generated by default on null as identity,
    organization_type      varchar2(30)   not null,
    organization_code      varchar2(150)  not null,
    organization_name      varchar2(240)  not null,
    parent_organization_id number,
    application_code       varchar2(30)   default 'COMMON' not null,
    source_type            varchar2(10)   default 'LOCAL' not null,
    fusion_organization_id varchar2(60),
    enabled_flag           varchar2(1)    default 'Y' not null,
    start_date_active      date           default trunc(sysdate) not null,
    end_date_active        date,
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxhr_organizations_pk primary key (organization_id),
    constraint xxhr_organizations_uk1 unique (organization_type, organization_code),
    constraint xxhr_organizations_fk1 foreign key (parent_organization_id) references xxhr_organizations (organization_id),
    constraint xxhr_organizations_fk2 foreign key (application_code) references xxfnd_applications (application_code),
    constraint xxhr_organizations_ck1 check (source_type in ('LOCAL','HCM')),
    constraint xxhr_organizations_ck2 check (enabled_flag in ('Y','N'))
)~');
    if l_new then
        xxfnd_ddl_pkg.run(q'~comment on table xxhr_organizations is 'Release 96: departments, organizations, business units and similar (ORGANIZATION_TYPE), the values of the data dimensions. LOCAL rows are kept here; HCM rows come from the Fusion HCM organizations API (FUSION_ORGANIZATION_ID) later.'~');
    end if;

    l_new := xxfnd_ddl_pkg.create_table('XXFND_DATA_DIMENSIONS', q'~create table xxfnd_data_dimensions (
    dimension_code         varchar2(30)   not null,
    dimension_name         varchar2(240)  not null,
    application_code       varchar2(30)   default 'COMMON' not null,
    value_source           varchar2(20)   default 'ORGANIZATION' not null,
    organization_type      varchar2(30),
    lookup_type            varchar2(30),
    enabled_flag           varchar2(1)    default 'Y' not null,
    description            varchar2(1000),
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_data_dimensions_pk primary key (dimension_code),
    constraint xxfnd_data_dimensions_fk1 foreign key (application_code) references xxfnd_applications (application_code),
    constraint xxfnd_data_dimensions_ck1 check (value_source in ('ORGANIZATION','LOOKUP','FREE')),
    constraint xxfnd_data_dimensions_ck2 check ((value_source = 'ORGANIZATION' and organization_type is not null)
                                             or (value_source = 'LOOKUP' and lookup_type is not null)
                                             or value_source = 'FREE'),
    constraint xxfnd_data_dimensions_ck3 check (enabled_flag in ('Y','N'))
)~');
    if l_new then
        xxfnd_ddl_pkg.run(q'~comment on table xxfnd_data_dimensions is 'Release 96: what data access is decided by (Department, Country, ...). Values: XXHR_ORGANIZATIONS of ORGANIZATION_TYPE, a lookup type, or FREE text.'~');
    end if;

    l_new := xxfnd_ddl_pkg.create_table('XXFND_DATA_OBJECTS', q'~create table xxfnd_data_objects (
    data_object_code       varchar2(60)   not null,
    object_name            varchar2(240)  not null,
    application_code       varchar2(30)   not null,
    table_name             varchar2(128)  not null,
    dimension_code         varchar2(30),
    dimension_column       varchar2(128),
    owner_column           varchar2(128),
    enabled_flag           varchar2(1)    default 'Y' not null,
    description            varchar2(1000),
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_data_objects_pk primary key (data_object_code),
    constraint xxfnd_data_objects_uk1 unique (table_name),
    constraint xxfnd_data_objects_fk1 foreign key (application_code) references xxfnd_applications (application_code) on delete cascade,
    constraint xxfnd_data_objects_fk2 foreign key (dimension_code) references xxfnd_data_dimensions (dimension_code),
    constraint xxfnd_data_objects_ck1 check ((dimension_code is null) = (dimension_column is null)),
    constraint xxfnd_data_objects_ck2 check (enabled_flag in ('Y','N'))
)~');
    if l_new then
        xxfnd_ddl_pkg.run(q'~comment on table xxfnd_data_objects is 'Release 96: a secured table of an application (row policy XXFND_DATA_SECURITY): DIMENSION_COLUMN holds the value of DIMENSION_CODE (level VALUES), OWNER_COLUMN the user who owns a record (level OWN).'~');
    end if;
    -- release 102: what DIMENSION_COLUMN holds - CODE (the value code, e.g. FINANCE) or ID (XXHR_ORGANIZATIONS.ORGANIZATION_ID
    -- of the dimension's organization type); access is still assigned by code
    xxfnd_ddl_pkg.add_column('XXFND_DATA_OBJECTS', 'DIMENSION_VALUE_TYPE', q'~varchar2(10) default 'CODE' not null~');
    xxfnd_ddl_pkg.add_constraint('XXFND_DATA_OBJECTS', 'XXFND_DATA_OBJECTS_CK3', q'~check (dimension_value_type in ('CODE','ID'))~');
    xxfnd_ddl_pkg.run(q'~comment on column xxfnd_data_objects.dimension_value_type is 'Release 102: CODE - DIMENSION_COLUMN holds the value code; ID - it holds XXHR_ORGANIZATIONS.ORGANIZATION_ID (dimensions of value source ORGANIZATION).'~');

    l_new := xxfnd_ddl_pkg.create_table('XXFND_ROLE_DATA_ACCESS', q'~create table xxfnd_role_data_access (
    role_data_access_id    number generated by default on null as identity,
    role_code              varchar2(30)   not null,
    data_object_code       varchar2(60)   not null,
    access_level           varchar2(10)   not null,
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_role_data_access_pk primary key (role_data_access_id),
    constraint xxfnd_role_data_access_uk1 unique (role_code, data_object_code, access_level),
    constraint xxfnd_role_data_access_fk1 foreign key (role_code) references xxfnd_roles (role_code) on delete cascade,
    constraint xxfnd_role_data_access_fk2 foreign key (data_object_code)
        references xxfnd_data_objects (data_object_code) on delete cascade,
    constraint xxfnd_role_data_access_ck1 check (access_level in ('ALL','VALUES','OWN'))
)~');
    if l_new then
        xxfnd_ddl_pkg.run(q'~create index xxfnd_role_data_access_n1 on xxfnd_role_data_access (data_object_code)~');
        xxfnd_ddl_pkg.run(q'~comment on table xxfnd_role_data_access is 'Release 96: which records of a data object a role reaches: ALL records, the given VALUES of the user''s role assignment, or OWN records.'~');
    end if;

    l_new := xxfnd_ddl_pkg.create_table('XXFND_ASSIGNMENT_VALUES', q'~create table xxfnd_assignment_values (
    assignment_value_id    number generated by default on null as identity,
    user_role_id           number         not null,
    dimension_code         varchar2(30)   not null,
    data_object_code       varchar2(60),
    value_code             varchar2(150)  not null,
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_assignment_values_pk primary key (assignment_value_id),
    constraint xxfnd_assignment_values_fk1 foreign key (user_role_id) references xxfnd_user_roles (user_role_id) on delete cascade,
    constraint xxfnd_assignment_values_fk2 foreign key (dimension_code) references xxfnd_data_dimensions (dimension_code),
    constraint xxfnd_assignment_values_fk3 foreign key (data_object_code)
        references xxfnd_data_objects (data_object_code) on delete cascade
)~');
    if l_new then
        xxfnd_ddl_pkg.run(q'~create unique index xxfnd_assignment_values_u1 on xxfnd_assignment_values
            (user_role_id, dimension_code, nvl(data_object_code, '#'), value_code)~');
        xxfnd_ddl_pkg.run(q'~comment on table xxfnd_assignment_values is 'Release 96: the values of a user''s role assignment per dimension. DATA_OBJECT_CODE empty = the default for every object of the dimension; set = an override for that object only (its values replace the default there).'~');
    end if;

    for t in (select column_value t from table(apex_t_varchar2('XXFND_USER_APPLICATIONS', 'XXFND_ROLE_MEMBERS',
                  'XXHR_ORGANIZATIONS', 'XXFND_DATA_DIMENSIONS', 'XXFND_DATA_OBJECTS', 'XXFND_ROLE_DATA_ACCESS',
                  'XXFND_ASSIGNMENT_VALUES'))) loop
        xxfnd_schema_pkg.create_who_trigger(t.t);
    end loop;
end;
