--------------------------------------------------------------------------------
-- XXFND_FI_DRIFT (release 107, Fusion Objects). COMMON only (XXFUSION).
--   Metadata drift found on an onboarded object (live metadata compared with the current version): non-breaking changes applied automatically, breaking ones waiting for approval.
-- Idempotent: created only when missing (XXFND_DDL_PKG.CREATE_TABLE); later changes are checked steps.
--------------------------------------------------------------------------------
begin
    if xxfnd_ddl_pkg.create_table('XXFND_FI_DRIFT', q'~create table xxfnd_fi_drift (
    drift_id               number generated by default on null as identity,
    object_id              number         not null,
    change_type            varchar2(10)   not null,
    attribute_name         varchar2(400)  not null,
    old_value              varchar2(400),
    new_value              varchar2(400),
    breaking_flag          varchar2(1)    default 'N' not null,
    status_code            varchar2(15)   default 'PENDING' not null,
    detected_date          timestamp      default systimestamp not null,
    decided_by             varchar2(255),
    decided_date           timestamp,
    -- standard WHO columns
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_fi_drift_pk primary key (drift_id),
    constraint xxfnd_fi_drift_fk1 foreign key (object_id) references xxfnd_fi_objects (object_id) on delete cascade,
    constraint xxfnd_fi_drift_ck1 check (change_type in ('ADDED', 'REMOVED', 'TYPE', 'LENGTH')),
    constraint xxfnd_fi_drift_ck2 check (breaking_flag in ('Y', 'N')),
    constraint xxfnd_fi_drift_ck3 check (status_code in ('AUTO_APPLIED', 'PENDING', 'APPROVED', 'REJECTED'))
)~') then
        xxfnd_ddl_pkg.run(q'~comment on table xxfnd_fi_drift is 'Release 107: metadata drift of an onboarded object. Non-breaking (added attribute, longer length) is applied automatically; breaking (removed attribute, type change, shorter length) waits on the Drift Queue (193) for an administrator.'~');
        xxfnd_ddl_pkg.run(q'~create index xxfnd_fi_drift_n1 on xxfnd_fi_drift (object_id, status_code)~');
    end if;
    xxfnd_schema_pkg.create_who_trigger('XXFND_FI_DRIFT');
end;
/
