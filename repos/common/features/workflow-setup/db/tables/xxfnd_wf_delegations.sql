
--------------------------------------------------------------------------------
-- 0.2  WORKFLOW: processes and tasks run on native APEX Workflow and Task
--      Definitions (APEX_WORKFLOW, APEX_HUMAN_TASK). This schema keeps only what
--      APEX does not: delegations (read by the task vacation rule procedure).
--------------------------------------------------------------------------------
begin
    if xxfnd_ddl_pkg.create_table('XXFND_WF_DELEGATIONS', q'~create table xxfnd_wf_delegations (
    delegation_id          number generated by default on null as identity,
    delegator_user_name    varchar2(255)  not null,
    delegate_user_name     varchar2(255)  not null,
    task_definition        varchar2(255),
    start_date             date           not null,
    end_date               date           not null,
    reason                 varchar2(1000),
    -- standard WHO columns
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_wf_delegations_pk primary key (delegation_id),
    constraint xxfnd_wf_delegations_ck1 check (end_date >= start_date),
    constraint xxfnd_wf_delegations_ck2 check (delegator_user_name <> delegate_user_name)
)~') then
        xxfnd_ddl_pkg.run(q'~create index xxfnd_wf_delegations_n1 on xxfnd_wf_delegations (delegator_user_name, start_date, end_date)~');
        xxfnd_ddl_pkg.run(q'~comment on table xxfnd_wf_delegations is 'Delegations (vacation rules): tasks of the delegator are also offered to the delegate between the dates. Read by XXFND_WORKFLOW_PKG.VACATION_RULE.'~');
        xxfnd_ddl_pkg.run(q'~comment on column xxfnd_wf_delegations.task_definition is 'Task definition static ID; null = every task.'~');
    end if;
end;
/
