-- 09f Central error handling (release 74). COMMON only (XXFUSION); every application uses it.
--   - XXFND_MESSAGES: the message catalogue (code + language -> text with {1}..{n} tokens). Packages raise by code
--     (XXFND_ERROR_PKG.RAISE_ERROR); a constraint name can also be a code, so a broken rule shows a readable message.
--     Administrators edit the texts; release 75 adds other languages.
--   - XXFND_ERROR_LOG: every unexpected error (user, application, page, component, error, stack), with a reference
--     number shown to the user.
--   - XXFND_ERROR_PKG.APEX_ERROR_HANDLER: the APEX error handling function of every application. Messages raised
--     by the application (ORA-20000..20999) are shown as they are; a known constraint shows its catalogue text;
--     anything else is logged and the user sees a friendly message with the reference.
--   Standard pattern in packages: catch only what you handle; to log and re-raise
--       when others then xxfnd_error_pkg.log_error('<package>.<procedure>'); raise;
-- Idempotent (CREATE_TABLE only when missing; changes as checked steps).
--------------------------------------------------------------------------------
begin
    if xxfnd_ddl_pkg.create_table('XXFND_MESSAGES', q'~create table xxfnd_messages (
    message_code           varchar2(128)  not null,
    language_code          varchar2(10)   default 'en' not null,
    message_text           varchar2(4000) not null,
    error_number           number(5),
    description            varchar2(1000),
    -- standard WHO columns
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_messages_pk primary key (message_code, language_code),
    constraint xxfnd_messages_ck1 check (error_number between -20999 and -20000)
)~') then
        xxfnd_ddl_pkg.run(q'~comment on table xxfnd_messages is 'Message catalogue: user messages by code and language ({1}..{n} = values). A constraint name as code gives that rule a readable message.'~');
        xxfnd_ddl_pkg.run(q'~comment on column xxfnd_messages.error_number is 'Oracle error number raised for the message (-20000..-20999); empty = -20000.'~');
    end if;
    xxfnd_schema_pkg.create_who_trigger('XXFND_MESSAGES');

    if xxfnd_ddl_pkg.create_table('XXFND_ERROR_LOG', q'~create table xxfnd_error_log (
    error_id               number generated by default on null as identity,
    error_time             timestamp with time zone default systimestamp not null,
    user_name              varchar2(255),
    application_id         number,
    page_id                number,
    session_id             number,
    request                varchar2(255),
    component              varchar2(1000),
    error_code             number,
    error_message          varchar2(4000),
    technical_info         clob,
    backtrace              clob,
    call_stack             clob,
    constraint xxfnd_error_log_pk primary key (error_id)
)~') then
        xxfnd_ddl_pkg.run(q'~create index xxfnd_error_log_n1 on xxfnd_error_log (error_time)~');
        xxfnd_ddl_pkg.run(q'~comment on table xxfnd_error_log is 'Unexpected errors of every application; ERROR_ID is the reference shown to the user.'~');
    end if;
end;
/

-- The common messages (administrators may change the texts; existing rows are kept).
merge into xxfnd_messages d
using (select 'XXFND_UNEXPECTED_ERROR' code, 'Something went wrong and the action was not completed. Please try again; if it happens again, contact support with reference {1}.' txt, null num, 'Shown for any unexpected error; {1} = the error log reference.' dsc from dual
       union all select 'XXFND_RECORD_CHANGED', 'This record was changed by someone else. Reload the page and try again.', -20001, 'Optimistic locking: the row changed since it was read.' from dual
       union all select 'XXFND_NOT_ALLOWED', 'You are not allowed to do this.', -20002, 'Generic authorisation failure.' from dual) s
   on (d.message_code = s.code and d.language_code = 'en')
 when not matched then insert (message_code, language_code, message_text, error_number, description)
                       values (s.code, 'en', s.txt, s.num, s.dsc);

-- messages (administrators may change the texts; existing rows are kept)
merge into xxfnd_messages d
using (select 'XXFND_APPROVAL_NO_RULE' code, 'No approval rule applies to this {1} transaction. Ask the administrator to add a rule in Approval Setup.' txt, -20531 num from dual
       union all select 'XXFND_APPROVAL_NOT_IN_PROGRESS', 'This approval is not in progress.', -20532 from dual
       union all select 'XXFND_APPROVAL_ADD_NOT_ALLOWED', 'Only the requester or the current approver can add an approver.', -20533 from dual
       union all select 'XXFND_APPROVAL_APPROVER_REQUIRED', 'Choose the role or the user to add as approver.', -20534 from dual
       -- release 76 (A-11)
       union all select 'XXFND_APPROVAL_NO_APPROVER', 'The approval step "{1}" has no approver: no active user holds the role {2}. Ask the administrator to give the role to a user or to change the rule in Approval Setup.', -20535 from dual) s
   on (d.message_code = s.code and d.language_code = 'en')
 when not matched then insert (message_code, language_code, message_text, error_number) values (s.code, 'en', s.txt, s.num);
commit;

-- messages of the RFI workflow (administrators may change the texts; existing rows are kept)
merge into xxfnd_messages d
using (select 'XXFND_RFI_QUESTION_REQUIRED' code, 'Enter the new question in Notes / New Question before asking again.' txt, -20508 num from dual) s
   on (d.message_code = s.code and d.language_code = 'en')
 when not matched then insert (message_code, language_code, message_text, error_number) values (s.code, 'en', s.txt, s.num);
commit;
