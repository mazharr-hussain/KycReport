begin
    if xxfnd_ddl_pkg.create_table('XXHR_EMPLOYEES', q'~create table xxhr_employees (
    employee_id            number generated by default on null as identity,
    source_type            varchar2(20)   default 'LOCAL' not null,
    fusion_person_id       number,
    fusion_person_number   varchar2(30),
    fusion_user_id         varchar2(64),
    user_name              varchar2(255)  not null,
    full_name              varchar2(240)  not null,
    email_address          varchar2(320)  not null,
    department_name        varchar2(240),
    job_title              varchar2(240),
    last_sync_date         timestamp,
    enabled_flag           varchar2(1)    default 'Y' not null,
    start_date_active      date           default trunc(sysdate) not null,
    end_date_active        date,
    -- standard WHO columns
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxhr_employees_pk primary key (employee_id),
    constraint xxhr_employees_uk1 unique (user_name),
    constraint xxhr_employees_uk2 unique (email_address),
    constraint xxhr_employees_ck1 check (source_type in ('FUSION','LOCAL')),
    constraint xxhr_employees_ck2 check (
        (source_type = 'FUSION' and fusion_person_id is not null) or
        (source_type = 'LOCAL'  and fusion_person_id is null)),
    constraint xxhr_employees_ck3 check (enabled_flag in ('Y','N')),
    constraint xxhr_employees_ck4 check (user_name = upper(user_name))
)~') then
        xxfnd_ddl_pkg.run(q'~create unique index xxhr_employees_u3 on xxhr_employees (fusion_person_id)~');
        xxfnd_ddl_pkg.run(q'~comment on table  xxhr_employees is 'One row per person. FUSION rows are maintained by the Fusion HCM sync and are read-only in the application; LOCAL rows are maintained by an administrator.'~');
        xxfnd_ddl_pkg.run(q'~comment on column xxhr_employees.user_name is 'Matches APP_USER after sign-in (upper case). This is how a session resolves to a person.'~');
    end if;
end;
