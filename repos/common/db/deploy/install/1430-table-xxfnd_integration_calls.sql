-- 05b XXFND_INTEGRATION_PKG (release 79; release 83: the Integrations component). COMMON only (XXFUSION).
--   Release 83: installed after the security objects (09b, privilege checks) and before the attachments (14), which
--   reach their document stores through it; it creates the HCM-owned-row trigger XXHR_EMPLOYEES_SRC (was in 08).
--   - Servers are APEX Remote Servers and their secrets APEX Web Credentials (workspace, kept by the workspace
--     administrator); endpoints are REST Data Sources of COMMON. XXFND_INTEGRATION_ENDPOINTS is read-only and
--     retiring: it is read only when no Remote Server of that static ID exists.
--   - CALL: the one call procedure (purpose -> REST Data Source -> Remote Server), logged in XXFND_INTEGRATION_CALLS
--     with what is needed to RETRY it; APEX logs every request in APEX_WEBSERVICE_LOG (Transmission Log, page 124).
--   - TEST_CONNECTION: one request to a server's base URL, kept per server (XXFND_SERVER_TESTS) for its health.
--   - SYNC_HCM: the Fusion HCM worker sync through purpose HCM_SYNC (server FUSION, REST Data Source
--     FUSION_HCM_WORKERS); the FUSION_* application settings are no longer read.
--   Release 86 (part B, workspace servers): XXFND_SERVERS - one row per server the COMMON administrator defines at
--     workspace level: SERVER_CODE = the APEX Remote Server static ID (its Web Credential holds the secret), the
--     server type (storage: OBJECT_STORAGE, SHAREPOINT, UCM; integration: FUSION, REST, OUTLOOK) and the type's
--     details. Created here (not in 29) because this package, the attachments (14), the communications seed (15e),
--     the setup rows (21c) and the modules state (22) use it and run before 29. XXFND_INTEGRATION_ENDPOINTS is
--     retired: 29 copies it into XXFND_SERVERS and drops it. A purpose may name its server (SERVER_CODE).
--     Saves of the Servers (121) and Purposes (123) screens: SAVE_SERVER / DELETE_SERVER, SAVE_PURPOSE / DELETE_PURPOSE.
-- Idempotent: tables only when missing, changes as checked steps; safe on install and on every upgrade.
--------------------------------------------------------------------------------
begin
    if xxfnd_ddl_pkg.create_table('XXFND_INTEGRATION_CALLS', q'~create table xxfnd_integration_calls (
    call_id                number generated by default on null as identity,
    purpose_code           varchar2(30),
    server_static_id       varchar2(255),
    rest_source_static_id  varchar2(255),
    http_method            varchar2(10)   not null,
    request_url            varchar2(4000) not null,
    request_path           varchar2(4000),
    request_query          varchar2(4000),
    request_body           clob,
    retryable_flag         varchar2(1)    default 'Y' not null,
    entity_name            varchar2(60),
    pk1_value              varchar2(150),
    status_code            varchar2(20)   default 'PENDING' not null,
    http_status            number(3),
    error_message          varchar2(4000),
    webservice_log_id      number,
    retry_of_call_id       number,
    called_by              varchar2(255)  not null,
    called_date            timestamp      default systimestamp not null,
    constraint xxfnd_integration_calls_pk primary key (call_id),
    constraint xxfnd_integration_calls_fk1 foreign key (retry_of_call_id) references xxfnd_integration_calls (call_id),
    constraint xxfnd_integration_calls_ck1 check (status_code in ('PENDING','SUCCESS','FAILED')),
    constraint xxfnd_integration_calls_ck2 check (retryable_flag in ('Y','N'))
)~') then
        xxfnd_ddl_pkg.run('create index xxfnd_integration_calls_n1 on xxfnd_integration_calls (entity_name, pk1_value)');
        xxfnd_ddl_pkg.run('create index xxfnd_integration_calls_n2 on xxfnd_integration_calls (server_static_id, called_date)');
        xxfnd_ddl_pkg.run('create index xxfnd_integration_calls_n3 on xxfnd_integration_calls (retry_of_call_id)');
        xxfnd_ddl_pkg.run(q'~comment on table xxfnd_integration_calls is 'Release 83: every call made through XXFND_INTEGRATION_PKG (purpose, server, record) with what is needed to retry it; the HTTP details are in APEX_WEBSERVICE_LOG (WEBSERVICE_LOG_ID). File transfers are logged but not retried (RETRYABLE_FLAG N).'~');
    end if;
end;
