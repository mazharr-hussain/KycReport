-- 13a Database document store (release 34): files are kept in the database when no UCM / SharePoint storage is
-- configured for the record (xxfnd_attach_pkg.resolve_storage falls back to storage type DATABASE).
-- Runs before 14 (XXFND_ATTACH_PKG reads and writes xxfnd_document_files; release 81: the store transport is in 14).

create table if not exists xxfnd_document_files (
    file_id        number generated by default on null as identity,
    file_content   blob                                   not null,
    created_by     varchar2(255) default coalesce(sys_context('APEX$SESSION', 'APP_USER'), user) not null,
    creation_date  timestamp     default systimestamp     not null,
    constraint xxfnd_document_files_pk primary key (file_id)
);
comment on table xxfnd_document_files is 'File bytes of attachments stored in the database (xxfnd_documents.storage_type = DATABASE; external_document_id / external_version_id = file_id). One row per version.';
