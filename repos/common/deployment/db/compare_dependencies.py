#!/usr/bin/env python3
"""Step 4.4 - the deployed schema's dependencies against the map generated from the source.

compare_dependencies.py <dependencies.json> <live.csv> <report.md>
The map (repos/common/db/deploy/dependencies.json, "uses") is generated by build.py from the source; the live list
comes from USER_DEPENDENCIES after the fresh deploy (db/dependencies.sql). Differences are listed in the report and
as one notice: a dependency the map does not know means the generated map (and its install order) is out of date.
Informational - it does not fail the pipeline; the install itself already proved the order works.
"""
import csv, json, sys

mapping, live_csv, report = sys.argv[1:4]
data = json.load(open(mapping))
# both directions of the map ("uses" and "used_by" are generated separately - take their union)
known = {(a, b) for a, refs in data.get('uses', {}).items() for b in refs}
known |= {(a, b) for b, users in data.get('used_by', {}).items() for a in users}
live = set()
with open(live_csv) as fh:
    for row in csv.DictReader(fh, skipinitialspace=True):
        row = {k.strip().strip('"').lower(): (v or '').strip().strip('"') for k, v in row.items() if k}
        if row.get('name'):
            live.add((row['name'], row['referenced_name']))
only_live = sorted(live - known)
only_map = sorted(k for k in known - live if k[0] in {a for a, _ in live})
with open(report, 'w') as out:
    out.write(f'# Dependency check\n\nLive dependencies: {len(live)} - in the generated map: {len(known)}\n\n')
    out.write(f'## In the database, not in the map ({len(only_live)})\n')
    out.writelines(f'- {a} -> {b}\n' for a, b in only_live)
    out.write(f'\n## In the map, not in the database ({len(only_map)})\n')
    out.writelines(f'- {a} -> {b}\n' for a, b in only_map)
print(f'dependency check: {len(live)} live, {len(known)} in the map; {len(only_live)} not in the map, '
      f'{len(only_map)} not in the database')
if only_live or only_map:   # information for the map generator (issue #212) - step log and report, no annotation
    print(f'info: {len(only_live)} live dependencies are not in the generated map and {len(only_map)} map entries '
          'are not in the database - see dependency-check.md in the report-6-dependencies artifact')
