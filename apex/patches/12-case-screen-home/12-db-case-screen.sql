--   XXCMP_APPROVAL_PATHS: the approval steps of a KYC request, maintained in setup (page 166).
--   One row per step: PATH_NAME groups the steps of one path; the path's criteria (department,
--   party type, country, request type; empty = any) choose it: the path matching the most criteria
--   wins, then the lowest PRIORITY. Each step is approved by a role or a named user.
--   XXCMP_APPROVAL_PKG: the path of a request, the current step's approvers, the path and history
--   shown on the request screens. The KYC_REQUEST workflow (1.3) runs one approval task per step.
-- Idempotent: safe on install and on every upgrade.
--------------------------------------------------------------------------------
create table if not exists xxcmp_approval_paths (
    approval_path_id       number generated by default on null as identity,
    path_name              varchar2(100)  not null,
    requesting_department  varchar2(240),
    party_type             varchar2(30),
    jurisdiction           varchar2(30),
    request_type           varchar2(30),
    priority               number         default 100 not null,
    step_sequence          number         not null,
    step_name              varchar2(100)  not null,
    approver_type          varchar2(10)   default 'ROLE' not null,
    role_code              varchar2(30),
    user_name              varchar2(255),
    enabled_flag           varchar2(1)    default 'Y' not null,
    created_by             varchar2(255)  not null,
    creation_date          timestamp      not null,
    last_updated_by        varchar2(255)  not null,
    last_update_date       timestamp      not null,
    last_update_login      varchar2(255),
    object_version_number  number         default 1 not null,
    constraint xxcmp_approval_paths_pk primary key (approval_path_id),
    constraint xxcmp_approval_paths_uk1 unique (path_name, step_sequence),
    constraint xxcmp_approval_paths_ck1 check (approver_type in ('ROLE', 'USER')),
    constraint xxcmp_approval_paths_ck2 check ((approver_type = 'ROLE' and role_code is not null)
                                            or (approver_type = 'USER' and user_name is not null)),
    constraint xxcmp_approval_paths_ck3 check (enabled_flag in ('Y', 'N'))
);
comment on table xxcmp_approval_paths is 'KYC request approval paths: one row per step; the path whose criteria match the request best applies.';
begin
    xxfnd_util_pkg.create_who_trigger('XXCMP_APPROVAL_PATHS');
    xxfnd_ddl_pkg.add_column('XXCMP_REQUESTS', 'APPROVAL_PATH_NAME', 'varchar2(100)');
    xxfnd_ddl_pkg.add_column('XXCMP_REQUESTS', 'CURRENT_STEP',       'number');
    -- release 26: paths by business relationship (customer, vendor...)
    xxfnd_ddl_pkg.add_column('XXCMP_APPROVAL_PATHS', 'BUSINESS_RELATIONSHIP', 'varchar2(30)');
end;
/
-- the default path (any request): one Compliance review
merge into xxcmp_approval_paths t
using (select 'Default' path_name, 1 step_sequence from dual) s
   on (t.path_name = s.path_name and t.step_sequence = s.step_sequence)
 when not matched then insert (path_name, priority, step_sequence, step_name, approver_type, role_code)
                       values ('Default', 999, 1, 'Compliance review', 'ROLE', 'COMPLIANCE_OFFICER');
commit;

-- one row of the approval history table (Global Page region Approval History)
create or replace type xxcmp_history_row force as object (
    step_no      number,
    step_name    varchar2(200),
    assigned_to  varchar2(1000),
    action       varchar2(100),
    action_by    varchar2(255),
    action_date  timestamp,
    comments     varchar2(4000)
