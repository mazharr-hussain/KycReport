-- 13a Database document store (release 34): files are kept in the database when no UCM / SharePoint storage is
-- configured for the record (xxfnd_attach_pkg.resolve_storage falls back to storage type DATABASE).
-- Runs before 13 (xxfnd_attach_store_pkg reads and writes xxfnd_document_files). Idempotent.

create table if not exists xxfnd_document_files (
    file_id        number generated by default on null as identity,
    file_content   blob                                   not null,
    created_by     varchar2(255) default coalesce(sys_context('APEX$SESSION', 'APP_USER'), user) not null,
    creation_date  timestamp     default systimestamp     not null,
    constraint xxfnd_document_files_pk primary key (file_id)
);
comment on table xxfnd_document_files is 'File bytes of attachments stored in the database (xxfnd_documents.storage_type = DATABASE; external_document_id / external_version_id = file_id). One row per version.';

-- a stored file may now be in the database
declare
    l_cond varchar2(4000);
begin
    select search_condition_vc into l_cond from user_constraints
     where table_name = 'XXFND_DOCUMENTS' and constraint_name = 'XXFND_DOCUMENTS_CK4';
    if instr(l_cond, 'DATABASE') = 0 then
        execute immediate 'alter table xxfnd_documents drop constraint xxfnd_documents_ck4';
        execute immediate q'[alter table xxfnd_documents add constraint xxfnd_documents_ck4 check (
            (datatype_code = 'FILE'     and storage_type in ('UCM','SHAREPOINT','DATABASE') and file_name is not null) or
            (datatype_code = 'WEB_PAGE' and url is not null and storage_type is null) or
            (datatype_code in ('SHORT_TEXT','LONG_TEXT') and storage_type is null))]';
    end if;
end;
