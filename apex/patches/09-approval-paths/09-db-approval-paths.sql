        begin
            if p_value is not null then
                l_html := l_html || '<dt class="t-AVPList-label">' || apex_escape.html(p_label) || '</dt>'
                               || '<dd class="t-AVPList-value">' || case when p_raw then p_value else apex_escape.html(p_value) end
                               || '</dd>';
            end if;
        end row;
    begin
