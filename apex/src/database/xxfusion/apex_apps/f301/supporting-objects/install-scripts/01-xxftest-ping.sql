-- Patch 102 test application 301: the one table, created only when it is missing (a re-run gives no error),
-- and one row per install that records the schema and user the install ran as.
declare
    l_count pls_integer;
begin
    select count(*) into l_count from user_tables where table_name = 'XXFTEST_PING';
    if l_count = 0 then
        execute immediate q'[
            create table xxftest_ping (
                ping_id      number generated by default on null as identity constraint xxftest_ping_pk primary key,
                installed_in varchar2(128) not null,
                session_user varchar2(128) not null,
                installed_on timestamp with time zone default systimestamp not null
            )]';
        execute immediate q'[comment on table xxftest_ping is 'Patch 102: one row per install of test application 301']';
    end if;
    execute immediate q'[insert into xxftest_ping (installed_in, session_user)
                         values (sys_context('userenv', 'current_schema'), sys_context('userenv', 'session_user'))]';
    commit;
end;
/
