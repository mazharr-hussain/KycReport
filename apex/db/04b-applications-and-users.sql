--------------------------------------------------------------------------------
-- 04b Applications and users - shared access module (release 46)
--   XXFND_APPLICATIONS: every APEX application that uses the shared access module. APPLICATION_ID is the APEX
--     application ID: the primary key, never changed; other tables refer to it (roles, features).
--   XXFND_USERS: the users of all applications. A user linked to an employee (USER_TYPE SSO) signs in with the
--     identity domain only; a LOCAL user (no employee) has an Oracle APEX account (APEX keeps the password),
--     created from the access console (XXFND_USER_PKG).
--   XXFND_USER_ROLES.USER_ID: grants belong to the user (EMPLOYEE_ID kept for the grants made before release 46;
--     trigger XXFND_USER_ROLES_USER fills USER_ID from it).
-- Idempotent: safe on install and on every upgrade.
--------------------------------------------------------------------------------
create table if not exists xxfnd_applications (
    application_id         number         not null,
    application_code       varchar2(30)   not null,
    application_name       varchar2(240)  not null,
    apex_app_alias         varchar2(255),
    enabled_flag           varchar2(1)    default 'Y' not null,
    description            varchar2(1000),
    -- standard WHO columns
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_applications_pk primary key (application_id),
    constraint xxfnd_applications_uk1 unique (application_code),
    constraint xxfnd_applications_ck1 check (enabled_flag in ('Y','N')),
    constraint xxfnd_applications_ck2 check (application_code = upper(application_code))
);
comment on table xxfnd_applications is 'Applications that use the shared access module (roles, features, users). APPLICATION_ID = the APEX application ID; never changed.';

create or replace trigger xxfnd_applications_id
before update of application_id on xxfnd_applications
for each row
when (new.application_id <> old.application_id)
begin
    raise_application_error(-20051, 'The application ID ' || :old.application_id || ' cannot be changed.');
end;
/

create table if not exists xxfnd_users (
    user_id                number generated by default on null as identity,
    user_name              varchar2(255)  not null,
    user_type              varchar2(10)   not null,
    employee_id            number,
    full_name              varchar2(240),
    email_address          varchar2(320),
    enabled_flag           varchar2(1)    default 'Y' not null,
    start_date_active      date           default trunc(sysdate) not null,
    end_date_active        date,
    description            varchar2(1000),
    -- standard WHO columns
    created_by               varchar2(255)  not null,
    creation_date            timestamp      not null,
    last_updated_by          varchar2(255)  not null,
    last_update_date         timestamp      not null,
    last_update_login        varchar2(255),
    object_version_number    number         default 1 not null,
    constraint xxfnd_users_pk primary key (user_id),
    constraint xxfnd_users_uk1 unique (user_name),
    constraint xxfnd_users_uk2 unique (employee_id),
    constraint xxfnd_users_fk1 foreign key (employee_id) references xxfnd_employees (employee_id),
    constraint xxfnd_users_ck1 check (user_type in ('SSO','LOCAL')),
    constraint xxfnd_users_ck2 check ((user_type = 'SSO' and employee_id is not null) or (user_type = 'LOCAL' and employee_id is null)),
    constraint xxfnd_users_ck3 check (enabled_flag in ('Y','N')),
    constraint xxfnd_users_ck4 check (user_name = upper(user_name)),
    constraint xxfnd_users_ck5 check (end_date_active is null or end_date_active >= start_date_active)
);
comment on table xxfnd_users is 'Users of all applications. SSO = linked to an employee, signs in with the identity domain (no password); LOCAL = no employee, Oracle APEX account (APEX keeps the password).';
comment on column xxfnd_users.user_name is 'Sign-in name, upper case. SSO: the employee''s user name (identity-domain user name); LOCAL: the APEX account name.';

declare
    procedure run(p_sql in varchar2) is
    begin
        execute immediate p_sql;
    exception
        when others then
            -- ORA-02275 / ORA-02261 / ORA-01451 / ORA-00955: the constraint / index already exists or the column is already nullable
            if sqlcode not in (-2275, -2261, -1451, -955) then
                raise;
            end if;
    end run;
begin
    -- roles and grants of the shared module refer to the application and the user
    xxfnd_ddl_pkg.add_column('XXFND_ROLES', 'APPLICATION_ID', 'number');
    xxfnd_ddl_pkg.add_column('XXFND_USER_ROLES', 'USER_ID', 'number');
    run('alter table xxfnd_user_roles modify (employee_id null)');
    run('alter table xxfnd_roles add constraint xxfnd_roles_fk1 foreign key (application_id) references xxfnd_applications (application_id)');
    run('alter table xxfnd_user_roles add constraint xxfnd_user_roles_fk3 foreign key (user_id) references xxfnd_users (user_id)');
    run('create index xxfnd_roles_n2 on xxfnd_roles (application_id)');
    run('create index xxfnd_user_roles_n3 on xxfnd_user_roles (user_id)');
    -- one open-ended grant per user and role
    -- ORA-02264: name already used by an existing constraint
    begin
        execute immediate 'alter table xxfnd_user_roles add constraint xxfnd_user_roles_ck3 check (user_id is not null) enable novalidate';
    exception when others then if sqlcode <> -2264 then raise; end if;
    end;
    run('create unique index xxfnd_user_roles_u2 on xxfnd_user_roles ('
        || 'case when end_date_active is null and user_id is not null then user_id end, '
        || 'case when end_date_active is null and user_id is not null then role_code end)');
end;
/

-- the KYC application (APEX application 134)
merge into xxfnd_applications t
using (select 134 application_id, 'KYC' application_code, 'KYC Compliance Platform' application_name, 'KYC' apex_app_alias from dual) s
   on (t.application_id = s.application_id)
 when not matched then insert (application_id, application_code, application_name, apex_app_alias,
                               created_by, creation_date, last_updated_by, last_update_date)
                       values (s.application_id, s.application_code, s.application_name, s.apex_app_alias,
                               'INSTALL', systimestamp, 'INSTALL', systimestamp);

-- existing roles belong to the application of their code
update xxfnd_roles r
   set r.application_id = (select a.application_id from xxfnd_applications a where a.application_code = r.application_code)
 where r.application_id is null
   and exists (select 1 from xxfnd_applications a where a.application_code = r.application_code);

-- every employee with a grant becomes an SSO user, and the grants move to the user
insert into xxfnd_users (user_name, user_type, employee_id, full_name, email_address, enabled_flag,
                         start_date_active, end_date_active,
                         created_by, creation_date, last_updated_by, last_update_date)
select upper(e.user_name), 'SSO', e.employee_id, e.full_name, e.email_address, e.enabled_flag,
       e.start_date_active, e.end_date_active, 'INSTALL', systimestamp, 'INSTALL', systimestamp
  from xxfnd_employees e
 where exists (select 1 from xxfnd_user_roles ur where ur.employee_id = e.employee_id)
   and not exists (select 1 from xxfnd_users u where u.employee_id = e.employee_id)
   and not exists (select 1 from xxfnd_users u where u.user_name = upper(e.user_name));

update xxfnd_user_roles ur
   set ur.user_id = (select u.user_id from xxfnd_users u where u.employee_id = ur.employee_id)
 where ur.user_id is null and ur.employee_id is not null;
commit;

-- a grant made for an employee (screens before release 46, the installer) goes to the employee's user, created
-- on the fly as an SSO user
create or replace trigger xxfnd_user_roles_user
before insert or update of employee_id, user_id on xxfnd_user_roles
for each row
when (new.user_id is null and new.employee_id is not null)
declare
    l_user_id xxfnd_users.user_id%type;
    l_emp     xxfnd_employees%rowtype;
begin
    select max(user_id) into l_user_id from xxfnd_users where employee_id = :new.employee_id;
    if l_user_id is null then
        select * into l_emp from xxfnd_employees where employee_id = :new.employee_id;
        insert into xxfnd_users (user_name, user_type, employee_id, full_name, email_address)
        values (upper(l_emp.user_name), 'SSO', l_emp.employee_id, l_emp.full_name, l_emp.email_address)
        returning user_id into l_user_id;
    end if;
    :new.user_id := l_user_id;
end;
/
