-- 09a Security model (release 96, agreed with the user): every row belongs to an application.
--   XXFND_USER_APPLICATIONS  a user's access to an application (one user, several applications)
--   XXFND_ROLE_MEMBERS       roles inside roles (a role = any mix of child roles, privileges and data access)
--   XXFND_ORGANIZATIONS      departments, organizations, business units ... (local now, Fusion HCM later)
--   XXFND_DATA_DIMENSIONS    what data access is decided by (Department, Country, ...) and where its values come from
--   XXFND_DATA_OBJECTS       a secured table: its dimension column and its owner column
--   XXFND_ROLE_DATA_ACCESS   role x data object x level (ALL records, given VALUES, OWN records)
--   XXFND_ASSIGNMENT_VALUES  the values of a user's role assignment per dimension (data object empty = the default
--                            for every object of the dimension; a data object = an override for that object only)
--   XXFND_USER_ROLE_TREE_V   a user's roles including the roles inside them (privileges and data access add up)
-- Data access only through roles (no direct grant to a user); it decides which records, privileges decide what.
-- Installed before 09b (its packages read these objects). Tables only when missing; a re-run changes nothing.
